#!/usr/bin/env python3
"""Collect gem5 stats from runs/<name>/ into results/results.csv and
results/summary.md (one table per experiment).

Usage: collect.py RUNS_DIR OUT_DIR
"""
import csv
import json
import os
import re
import sys

STATS = {
    "sim_insts": "simInsts",
    "sim_seconds": "simSeconds",
    "cycles": "system.cpu.numCycles",
    "ipc": "system.cpu.ipc",
    "cpi": "system.cpu.cpi",
    "t0_insts": "system.cpu.commitStats0.numInsts",
    "t0_ipc": "system.cpu.commitStats0.ipc",
    "t1_insts": "system.cpu.commitStats1.numInsts",
    "t1_ipc": "system.cpu.commitStats1.ipc",
    "bp_lookups": "system.cpu.branchPred.lookups_0::total",
    "cond_predicted": "system.cpu.branchPred.condPredicted",
    "cond_incorrect": "system.cpu.branchPred.condIncorrect",
    "commit_mispredicts": "system.cpu.commit.branchMispredicts",
    "squashed_issued": "system.cpu.squashedInstsIssued",
    "insts_issued": "system.cpu.instsIssued",
    "issued_per_cycle": "system.cpu.numIssuedDist::mean",
    "committed_per_cycle": "system.cpu.commit.numCommittedDist::mean",
    "rob_full": "system.cpu.rename.ROBFullEvents",
    "iq_full": "system.cpu.rename.IQFullEvents",
    "lq_full": "system.cpu.rename.LQFullEvents",
    "sq_full": "system.cpu.rename.SQFullEvents",
    "fu_busy": "system.cpu.fuBusy::total",
    "fu_busy_rate": "system.cpu.fuBusyRate::total",
    "fu_busy_t0": "system.cpu.fuBusy::0",
    "fu_busy_t1": "system.cpu.fuBusy::1",
    "dcache_miss_rate": "system.cpu.dcache.overallMissRate::total",
    "icache_miss_rate": "system.cpu.icache.overallMissRate::total",
}
LINE = re.compile(r"^(\S+)\s+(\S+)")


def read_stats(path):
    vals = {}
    with open(path) as f:
        for line in f:
            if line.startswith("---------- End"):
                break  # first stats dump only
            m = LINE.match(line)
            if m:
                vals[m.group(1)] = m.group(2)
    return vals


def num(x):
    try:
        v = float(x)
        return v
    except (TypeError, ValueError):
        return None


def parse_name(name):
    d = {"name": name, "cpu": "", "width": "", "bp": "", "bin": "", "bin2": ""}
    if name.startswith("minor_"):
        d.update(experiment="A_pipeline", cpu="minor", width=1,
                 bp="(none: MinorCPU x86 makes no lookups)", bin=name[6:])
    elif name.startswith("smt_"):
        _, w, pair = name.split("_", 2)
        a, b = pair.split("+")
        d.update(experiment="D_smt", cpu="o3", width=int(w[1:]),
                 bp="tournament", bin=a, bin2=b)
    else:
        w, bp, wl = name.split("_", 2)
        d.update(cpu="o3", width=int(w[3:]), bp=bp, bin=wl)
        d["experiment"] = "B_branch" if (bp != "tournament" or
                                         wl == "branch_pat") else "C_width"
    return d


def main(runs, out):
    os.makedirs(out, exist_ok=True)
    rows = []
    for name in sorted(os.listdir(runs)):
        sp = os.path.join(runs, name, "stats.txt")
        if not os.path.exists(sp):
            continue
        st = read_stats(sp)
        row = parse_name(name)
        for k, s in STATS.items():
            row[k] = st.get(s, "")
        cp = num(row["cond_predicted"])
        ci = num(row["cond_incorrect"])
        row["mispredict_rate"] = (round(ci / cp, 4) if cp else "")
        lj = os.path.join(runs, name, "latency.json")
        if os.path.exists(lj):
            lat = json.load(open(lj))
            key = "fetch_to_retire" if row["cpu"] == "o3" else "fetch_to_commit"
            s = lat.get(key) or {}
            row["latency_mean_cycles"] = s.get("mean", "")
            row["latency_median_cycles"] = s.get("median", "")
            row["latency_insts_measured"] = s.get("n", "")
            if row["cpu"] == "minor":
                s2 = lat.get("fetch2_to_commit") or {}
                row["fetch2_to_commit_mean"] = s2.get("mean", "")
            row["stage_avg_cycles"] = json.dumps(
                lat.get("stage_avg_cycles", {}))
        con = os.path.join(runs, name, "console.log")
        if os.path.exists(con):
            m = re.search(r"wall_seconds=(\d+)", open(con).read())
            row["wall_seconds"] = m.group(1) if m else ""
        rows.append(row)

    fields = []
    for r in rows:
        for k in r:
            if k not in fields:
                fields.append(k)
    with open(os.path.join(out, "results.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    by = {r["name"]: r for r in rows}

    def f(x, nd=3):
        v = num(x)
        return "" if v is None else (f"{v:,.{nd}f}" if nd else f"{v:,.0f}")

    md = ["# Assignment 4 Part 2 - results summary",
          "", "Generated by `collect.py` from `runs/*/stats.txt`. "
          "Latency = per-instruction fetch-to-commit (MinorCPU) or "
          "fetch-to-retire (O3), averaged over a 20,000-cycle trace window.",
          ""]

    md += ["## A. Basic pipeline (MinorCPU, in-order, single issue)", "",
           "| Workload | Instructions | Cycles | IPC (throughput) | CPI | "
           "Avg latency (cycles) | Fetch2-to-commit (cycles) | D-cache miss rate |",
           "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rows:
        if r["experiment"] == "A_pipeline":
            md.append(f"| {r['bin']} | {f(r['sim_insts'],0)} | {f(r['cycles'],0)} | "
                      f"{f(r['ipc'])} | {f(r['cpi'])} | "
                      f"{f(r.get('latency_mean_cycles'),1)} | "
                      f"{f(r.get('fetch2_to_commit_mean'),1)} | "
                      f"{f(r['dcache_miss_rate'],4)} |")

    md += ["", "## B. Branch prediction (O3)", "",
           "`none` = static predict-not-taken (StaticNotTakenBP).", "",
           "| Width | Predictor | Workload | IPC | Cycles | Cond. mispredict rate | "
           "Squashed insts issued | Avg latency (cycles) |",
           "|---:|---|---|---:|---:|---:|---:|---:|"]
    order = ["none", "local", "bimode", "tournament", "ltage"]
    for width in (1, 4):
        for wl in ("branch_rand", "branch_pat", "int_work"):
            for bp in order:
                r = by.get(f"o3w{width}_{bp}_{wl}")
                if r:
                    md.append(f"| {width} | {bp} | {wl} | {f(r['ipc'])} | "
                              f"{f(r['cycles'],0)} | {f(r['mispredict_rate'],4)} | "
                              f"{f(r['squashed_issued'],0)} | "
                              f"{f(r.get('latency_mean_cycles'),1)} |")

    md += ["", "## C. Multiple issue (O3, tournament predictor)", "",
           "Speedup is cycles(MinorCPU) / cycles(O3 at width W) for the same "
           "workload, so >1 means faster than the single-issue in-order pipeline.", "",
           "| Workload | MinorCPU IPC | W=1 IPC | W=2 IPC | W=4 IPC | W=8 IPC | "
           "Speedup W=8 vs Minor | Speedup W=8 vs W=1 |",
           "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for wl in ("int_work", "fp_work", "mem_work", "branch_rand"):
        mi = by.get(f"minor_{wl}")
        ws = [by.get(f"o3w{w}_tournament_{wl}") for w in (1, 2, 4, 8)]
        cells = [f(x["ipc"]) if x else "" for x in ws]
        sp_m = sp_1 = ""
        if mi and ws[3]:
            sp_m = f"{num(mi['cycles']) / num(ws[3]['cycles']):.2f}x"
        if ws[0] and ws[3]:
            sp_1 = f"{num(ws[0]['cycles']) / num(ws[3]['cycles']):.2f}x"
        md.append(f"| {wl} | {f(mi['ipc']) if mi else ''} | " + " | ".join(cells)
                  + f" | {sp_m} | {sp_1} |")

    md += ["", "## D. SMT (2 threads, one O3 core, tournament predictor)", "",
           "Single-thread IPC is from the same core width running each program "
           "alone. Combined speedup = (cycles A alone + cycles B alone) / cycles "
           "of the SMT run.", "",
           "| Width | Thread 0 | Thread 1 | Core IPC (SMT) | T0 IPC | T1 IPC | "
           "Alone IPC T0 / T1 | Combined speedup | ROB full | IQ full | LQ/SQ full | FU busy |",
           "|---:|---|---|---:|---:|---:|---|---:|---:|---:|---:|---:|"]
    for r in rows:
        if r["experiment"] != "D_smt":
            continue
        w = r["width"]
        a = by.get(f"o3w{w}_tournament_{r['bin']}")
        b = by.get(f"o3w{w}_tournament_{r['bin2']}")
        alone = (f"{f(a['ipc'])} / {f(b['ipc'])}" if a and b else "")
        sp = ""
        if a and b:
            sp = f"{(num(a['cycles']) + num(b['cycles'])) / num(r['cycles']):.2f}x"
        lsq = f"{f(r['lq_full'],0)} / {f(r['sq_full'],0)}"
        md.append(f"| {w} | {r['bin']} | {r['bin2']} | {f(r['ipc'])} | "
                  f"{f(r['t0_ipc'])} | {f(r['t1_ipc'])} | {alone} | {sp} | "
                  f"{f(r['rob_full'],0)} | {f(r['iq_full'],0)} | {lsq} | "
                  f"{f(r['fu_busy'],0)} |")

    with open(os.path.join(out, "summary.md"), "w") as fo:
        fo.write("\n".join(md) + "\n")
    print("\n".join(md))
    print(f"\n{len(rows)} runs -> {out}/results.csv, {out}/summary.md")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
